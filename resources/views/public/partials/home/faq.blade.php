        <details class="faq-item">
            <summary>Perlu akun untuk melihat kamar?</summary>
            <p>Tidak. Halaman kos dan daftar kamar bisa dilihat siapa saja. Akun diperlukan saat mengajukan sewa.</p>
        </details>

        <details class="faq-item">
            <summary>Bagaimana cara mengajukan sewa?</summary>
            <p>Buat akun penghuni, pilih kamar kosong, isi formulir pemesanan. Pengurus akan meninjau dan menyetujui dari dashboard mereka.</p>
        </details>

        <details class="faq-item">
            <summary>Format bukti bayar apa yang diterima?</summary>
            <p>JPEG, PNG, atau PDF maksimal 2 MB. Bukti hanya bisa dilihat pengurus kos terkait, tidak lewat URL publik.</p>
        </details>

        <details class="faq-item">
            <summary>Laporan bisa diunduh?</summary>
            <p>Ya. Pengurus bisa unduh laporan pembayaran per bulan atau per periode dalam format PDF.</p>
        </details>
    </div>
